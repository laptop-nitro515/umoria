// Runs the original C++ random number code with fixed seeds and writes the
// results out as C# test data. The C# tests assert the port reproduces them.

#include "headers.h"

#include <fstream>
#include <vector>

void seedsInitialize(uint32_t seed);
int randomNumber(int max);
int randomNumberNormalDistribution(int mean, int standard);

static void list(std::ostream &o, const char *name, const std::vector<long long> &v) {
    o << "        public static readonly long[] " << name << " = {";
    for (size_t i = 0; i < v.size(); i++) {
        o << (i % 10 == 0 ? "\n            " : " ") << v[i] << ",";
    }
    o << "\n        };\n\n";
}

static const uint32_t seeds[] = {1u, 12345u, 987654321u, 4000000000u};

int main(int argc, char **argv) {
    if (argc != 2) {
        fprintf(stderr, "usage: %s <output-file>\n", argv[0]);
        return 1;
    }
    std::ofstream o(argv[1]);
    o << "// SPDX-License-Identifier: GPL-3.0-or-later\n"
         "//\n"
         "// <auto-generated>\n"
         "// Generated by unity/tools/export_golden.cpp from the original C++ code. Do not edit by hand.\n"
         "// </auto-generated>\n\n"
         "namespace Umoria.Core.Tests\n{\n    public static class GoldenValues\n    {\n";

    list(o, "Seeds", {1, 12345, 987654321, 4000000000LL});

    // Park-Miller self check: seed 0 -> z[10001]
    setRandomSeed(0);
    for (int i = 1; i < 10000; i++) (void) rnd();
    o << "        public const long Rnd10001 = " << rnd() << ";\n\n";

    for (int s = 0; s < 4; s++) {
        std::string sfx = std::to_string(s);
        std::vector<long long> v;

        setRandomSeed(seeds[s]);
        for (int i = 0; i < 50; i++) v.push_back(rnd());
        list(o, ("Rnd" + sfx).c_str(), v);

        v.clear();
        setRandomSeed(seeds[s]);
        for (int i = 0; i < 50; i++) v.push_back(randomNumber(100));
        list(o, ("RandomNumber100_" + sfx).c_str(), v);

        v.clear();
        setRandomSeed(seeds[s]);
        for (int i = 0; i < 200; i++) v.push_back(randomNumberNormalDistribution(100, 15));
        list(o, ("Normal100_15_" + sfx).c_str(), v);

        v.clear();
        setRandomSeed(seeds[s]);
        for (int i = 0; i < 50; i++) v.push_back(diceRoll(Dice_t{3, 6}));
        list(o, ("Dice3d6_" + sfx).c_str(), v);

        v.clear();
        seedsInitialize(seeds[s]);
        v.push_back(game.magic_seed);
        v.push_back(game.town_seed);
        for (int i = 0; i < 10; i++) v.push_back(rnd());
        list(o, ("SeedsInitialize_" + sfx).c_str(), v);
    }

    o << "    }\n}\n";
    return 0;
}
