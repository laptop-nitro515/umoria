int main(int argc, char **argv) {
    if (argc != 2) {
        fprintf(stderr, "usage: %s <output-dir>\n", argv[0]);
        return 1;
    }
    std::string dir = argv[1];
    creatures(dir);
    treasure(dir);
    player(dir);
    recall(dir);
    storeTables(dir);
    tables(dir);
    return 0;
}
