static void player(const std::string &dir) {
    std::ofstream o(dir + "/PlayerData.cs");
    header(o, "data_player.cpp");
    o << "    public static class PlayerData\n    {\n";

    o << "        public static readonly string[][] ClassRankTitles =\n        {\n";
    for (int c = 0; c < PLAYER_MAX_CLASSES; c++) {
        o << "            new[]\n            {\n";
        for (int l = 0; l < PLAYER_MAX_LEVEL; l++) {
            o << "                " << esc(class_rank_titles[c][l]) << ",\n";
        }
        o << "            },\n";
    }
    o << "        };\n\n";

    o << "        public static readonly Race[] Races =\n        {\n";
    for (int i = 0; i < PLAYER_MAX_RACES; i++) {
        const Race_t &r = character_races[i];
        o << "            new Race(" << esc(r.name) << ", " << r.str_adjustment << ", " << r.int_adjustment << ", " << r.wis_adjustment << ", "
          << r.dex_adjustment << ", " << r.con_adjustment << ", " << r.chr_adjustment << ",\n                " << (int) r.base_age << ", "
          << (int) r.max_age << ", " << (int) r.male_height_base << ", " << (int) r.male_height_mod << ", " << (int) r.male_weight_base << ", "
          << (int) r.male_weight_mod << ", " << (int) r.female_height_base << ", " << (int) r.female_height_mod << ", "
          << (int) r.female_weight_base << ", " << (int) r.female_weight_mod << ",\n                " << r.disarm_chance_base << ", "
          << r.search_chance_base << ", " << r.stealth << ", " << r.fos << ", " << r.base_to_hit << ", " << r.base_to_hit_bows << ", "
          << r.saving_throw_base << ", " << (int) r.hit_points_base << ", " << (int) r.infra_vision << ", " << (int) r.exp_factor_base << ", 0x"
          << std::hex << (int) r.classes_bit_field << std::dec << "),\n";
    }
    o << "        };\n\n";

    o << "        // info, roll, chart, next, bonus\n";
    o << "        public static readonly Background[] Backgrounds =\n        {\n";
    for (int i = 0; i < PLAYER_MAX_BACKGROUNDS; i++) {
        const Background_t &b = character_backgrounds[i];
        o << "            new Background(" << esc(b.info) << ", " << (int) b.roll << ", " << (int) b.chart << ", " << (int) b.next << ", "
          << (int) b.bonus << "),\n";
    }
    o << "        };\n\n";

    o << "        public static readonly Class[] Classes =\n        {\n";
    for (int i = 0; i < PLAYER_MAX_CLASSES; i++) {
        const Class_t &c = classes[i];
        o << "            new Class(" << esc(c.title) << ", " << (int) c.hit_points << ", " << (int) c.disarm_traps << ", " << (int) c.searching << ", "
          << (int) c.stealth << ", " << (int) c.fos << ", " << (int) c.base_to_hit << ", " << (int) c.base_to_hit_with_bows << ", "
          << (int) c.saving_throw << ", " << c.strength << ", " << c.intelligence << ", " << c.wisdom << ", " << c.dexterity << ", "
          << c.constitution << ", " << c.charisma << ", " << (int) c.class_to_use_mage_spells << ", " << (int) c.experience_factor << ", "
          << (int) c.min_level_for_spell_casting << "),\n";
    }
    o << "        };\n\n";

    ints2(o, "short", "ClassLevelAdjustments", &class_level_adj[0][0], PLAYER_MAX_CLASSES, CLASS_MAX_LEVEL_ADJUST);

    o << "        // Warriors have no spells, so index with class_id - 1.\n";
    o << "        // level_required, mana_required, failure_chance, exp_gain_for_learning\n";
    o << "        public static readonly Spell[][] MagicSpells =\n        {\n";
    for (int c = 0; c < PLAYER_MAX_CLASSES - 1; c++) {
        o << "            new[]\n            {\n";
        for (int s = 0; s < 31; s++) {
            const Spell_t &sp = magic_spells[c][s];
            o << "                new Spell(" << (int) sp.level_required << ", " << (int) sp.mana_required << ", " << (int) sp.failure_chance
              << ", " << (int) sp.exp_gain_for_learning << "),\n";
        }
        o << "            },\n";
    }
    o << "        };\n\n";

    strings(o, "SpellNames", spell_names, 62);
    ints2(o, "ushort", "ClassBaseProvisions", &class_base_provisions[0][0], PLAYER_MAX_CLASSES, 5);
    o << "    }\n}\n";
}

